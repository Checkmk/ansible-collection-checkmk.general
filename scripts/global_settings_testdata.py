#!/usr/bin/env python
#
# Written by: Robin Gierse - robin.gierse@checkmk.com - on 20261006
#
# Purpose:
# Generate the test data of the global_setting integration target: every global
# setting of a Checkmk site with its value, written the way the GUI shows it.
#
# The REST API has no endpoint that lists the global settings, so the list is
# read from the registry of the site itself. That needs the site to be local:
# the script runs a short piece of itself as the site user via 'sudo'. The
# values are then read through the REST API and translated with the same code
# the module and the lookup use.
#
# Run it against a site created with plain 'omd create', and give the site a
# distinctive name: every occurrence of the site ID in a value is replaced by the
# site variable of the tests. Sites from 'cmk-dev-install-site' do not fit, as
# it changes OMD options (autostart, Livestatus TCP, tracing) that some global
# settings reflect. For example:
#   sudo omd -V 3.0.0-2026.10.06.ultimatemt create --admin-password cmk gsgen
#   sudo omd start gsgen
#
# Usage:
#   Write tests/integration/targets/global_setting/vars/settings.yml:
#     uv run scripts/global_settings_testdata.py -s mysite
#   Write somewhere else:
#     uv run scripts/global_settings_testdata.py -s mysite -o /tmp/settings.yml
#   With explicit credentials:
#     uv run scripts/global_settings_testdata.py -s mysite -a myuser -p mysecret
#
# Credentials default to the ones 'cmk-dev-install-site' configures on a local
# development site. Override them with '-a' and '-p', or by exporting
# CHECKMK_VAR_API_USER and CHECKMK_VAR_API_SECRET.

import argparse
import base64
import importlib.util
import itertools
import json
import os
import re
import subprocess
import sys
import urllib.request

COLLECTION_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUTPUT = os.path.join(
    COLLECTION_DIR, "tests/integration/targets/global_setting/vars/settings.yml"
)

# Non-default values the tests change settings to.
EXAMPLES = {
    "wato_hide_varnames": False,
    "wato_max_snapshots": 100,
    "page_heading": "Checkmk Playground - %s",
    "adhoc_downtime": {
        "Ad hoc comment": "Ad hoc downtime on the Checkmk Playground",
        "Duration": 60,
    },
    "session_mgmt": {
        "Maximum session duration": {
            "Advise re-authentication before termination": "15min",
            "Enforce re-authentication after": "1d",
        },
        "Set an individual idle timeout": "8h",
    },
    "notification_backlog": 50,
    "failed_notification_horizon": "1d",
    "reporting_filename": "checkmk-playground-report.pdf",
    "history_lifetime": 90,
    "log_rulehits": True,
}

# Holds the certificates of the site itself, so the tests read it from the site.
FROM_SITE = {"trusted_certificate_authorities"}

# Checkmk rejects its own factory value as input (3.0.0-2026.10.06: the
# comment must not be empty), so the tests cannot write it back.
INVALID_DEFAULT = {"adhoc_downtime"}

# Password used in place of the masked passwords of a new site.
TEST_PASSWORD = "Sup3rSec4et!"

# File-friendly names of the GUI groups. Unlisted groups are derived from the title.
CATEGORIES = {
    "ntopng (chargeable add-on)": "ntopng",
    "Automatic agent updates": "agent_updates",
    "Maps: Map and object defaults": "maps_defaults",
    "Maps: Connections & daemon": "maps_connections",
    "Event Console: generic": "event_console",
    "Event Console: logging & diagnose": "event_console_logging",
    "Event Console: SNMP traps": "event_console_snmp_traps",
}

HEADER = """---
# Every global setting of Checkmk {version}, grouped like the GUI.
# Generated by scripts/global_settings_testdata.py, do not edit by hand.
#
#   value:      the value of a new site, written the way the GUI shows it
#   example:    a non-default value to change the setting to
#   preset:     Checkmk configures the setting on new sites (origin 'global')
#   secret:     contains a password, see the secrets block in all_settings.yml
#   from_site:  the value is site-specific and read from the site first
#   resettable: false when Checkmk refuses to reset the setting
#   invalid_default: Checkmk rejects its own factory value as input
"""


def dump_registry():
    """Print the global settings this site offers. Runs as the site user."""
    from cmk.ccc.version import edition
    from cmk.gui import main_modules
    from cmk.gui.wsgi.app import gui_context
    from cmk.utils import paths

    main_modules.register(edition(paths.omd_root))
    with gui_context():
        from cmk.gui.global_config import get_global_config
        from cmk.gui.watolib.config_domain_name import (
            ABCConfigDomain,
            config_variable_registry,
        )
        from cmk.gui.watolib.global_settings import is_available_in_global_settings

        defaults = ABCConfigDomain.get_all_default_globals()
        is_activated = get_global_config().global_settings.is_activated
        settings = []
        for varname, variable in config_variable_registry.items():
            if not is_available_in_global_settings(
                variable, default_values=defaults, is_activated=is_activated
            ):
                continue
            group = variable.group()
            settings.append(
                {
                    "varname": varname,
                    "group": group.title(),
                    "group_sort": group.sort_index(),
                    "event_console": variable.primary_domain().ident() == "ec",
                    "allow_reset": variable.allow_reset(),
                }
            )
    json.dump(settings, sys.stdout)


def read_registry(site):
    with open(os.path.abspath(__file__), "rb") as script:
        result = subprocess.run(
            ["sudo", "-iu", site, "python3", "-I", "-", "--registry"],
            stdin=script,
            capture_output=True,
            check=True,
        )
    return json.loads(result.stdout)


def load_module_utils():
    path = os.path.join(COLLECTION_DIR, "plugins/module_utils/global_settings.py")
    spec = importlib.util.spec_from_file_location("global_settings", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class Api:
    def __init__(self, server_url, site, user, secret):
        self.base = "%s/%s/check_mk/api" % (server_url.rstrip("/"), site)
        token = base64.b64encode(("%s:%s" % (user, secret)).encode()).decode()
        self.headers = {"Authorization": "Basic " + token, "Accept": "application/json"}

    def get(self, path):
        request = urllib.request.Request(self.base + path, headers=self.headers)
        with urllib.request.urlopen(request) as response:
            return json.load(response)


def category(group):
    return CATEGORIES.get(group) or re.sub(r"[^a-z0-9]+", "_", group.lower()).strip("_")


def site_neutral(value, site, hidden):
    """Replace the site ID by the variable the tests use, and set masked passwords.

    Dictionary keys are sorted, so that regenerating for a new build only shows
    real changes.
    """
    text = json.dumps(value, sort_keys=True)  # stable diffs between builds
    # Also inside names like 'cmk_mysite', so '_' may precede the site ID.
    text = re.sub(
        r"(?<![A-Za-z0-9-])%s(?![\w-])" % re.escape(site),
        "{{ outer_item.site }}",
        text,
    )
    text = text.replace(json.dumps(hidden), json.dumps(TEST_PASSWORD))
    return json.loads(text)


def build(registry, api, site, module_utils):
    hidden = module_utils.HIDDEN_SECRET
    ordered = sorted(
        registry, key=lambda s: (s["event_console"], s["group_sort"], s["group"])
    )
    data = {}
    for group, members in itertools.groupby(ordered, key=lambda s: s["group"]):
        entries = []
        for setting in members:
            varname = setting["varname"]
            ui = module_utils.ui_from_setting(
                api.get("/internal/" + module_utils.setting_endpoint(varname))
            )
            entry = {"name": varname}
            if varname not in FROM_SITE:
                entry["value"] = site_neutral(ui["value"], site, hidden)
            if varname in EXAMPLES:
                entry["example"] = EXAMPLES[varname]
            if ui["origin"] != "factory":
                entry["preset"] = True
            if hidden in json.dumps(ui["value"]):
                entry["secret"] = True
            if varname in FROM_SITE:
                entry["from_site"] = True
            if varname in INVALID_DEFAULT:
                entry["invalid_default"] = True
            if not setting["allow_reset"]:
                entry["resettable"] = False
            entries.append((ui["title"].lower(), entry))
        data[category(group)] = [
            entry for _title, entry in sorted(entries, key=lambda e: e[0])
        ]
    return data


def dump_yaml(data, version):
    import yaml

    class Dumper(yaml.SafeDumper):
        """Indented sequences and double quotes, as the repository's yamllint wants."""

        def increase_indent(self, flow=False, indentless=False):
            return super().increase_indent(flow, False)

        def choose_scalar_style(self):
            style = super().choose_scalar_style()
            return '"' if style == "'" else style

    body = yaml.dump(
        {"checkmk_var_global_settings": data},
        Dumper=Dumper,
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=False,
        width=100,
    )
    return HEADER.format(version=version) + body


def main():
    parser = argparse.ArgumentParser(
        description="Generate the test data of the global_setting integration target."
    )
    parser.add_argument("-s", "--site", required=True, help="local site to read from")
    parser.add_argument("-U", "--server-url", default="http://localhost")
    parser.add_argument(
        "-a", "--api-user", default=os.environ.get("CHECKMK_VAR_API_USER", "cmkadmin")
    )
    parser.add_argument(
        "-p", "--api-secret", default=os.environ.get("CHECKMK_VAR_API_SECRET", "cmk")
    )
    parser.add_argument("-o", "--output", default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    module_utils = load_module_utils()

    api = Api(args.server_url, args.site, args.api_user, args.api_secret)
    version = api.get("/1.0/version")["versions"]["checkmk"]
    registry = read_registry(args.site)
    data = build(registry, api, args.site, module_utils)

    with open(args.output, "w") as output:
        output.write(dump_yaml(data, version))
    print(
        "%d settings in %d categories of %s written to %s"
        % (sum(map(len, data.values())), len(data), version, args.output)
    )


if __name__ == "__main__":
    if sys.argv[1:] == ["--registry"]:
        dump_registry()
    else:
        main()
